import { evaluate, modulesDoneBy, validate } from '../../src/core/optimizer/evaluate';
import { optimize } from '../../src/core/optimizer/search';
import { parseFlags, prepare } from './common';

const flags = parseFlags();
const seedArg = flags.get('seed', '1')!;
const qIters = flags.get('iters', '300000')!;
const oIters = flags.get('order-iters', '20000')!;
const { inst, appQueues } = prepare(flags);
const app = evaluate(inst, appQueues);
const t0 = Date.now();
const weights = { makespan: Number(process.env.W_MAKESPAN ?? 0.3), partEnd: Number(process.env.W_PARTEND ?? 0.0015), setup: Number(process.env.W_SETUP ?? 0) };
const res = optimize(inst, { seed: Number(seedArg), queueIters: Number(qIters), orderIters: Number(oIters), restarts: Number(process.env.RESTARTS ?? 3), weights, starts: [appQueues], log: s => console.log(s) });
console.log(`done in ${((Date.now() - t0) / 1000).toFixed(1)}s`);
console.log('app    sumC', app.sumC, 'makespan', app.makespan, 'setup', app.setupTotal);
console.log('best   sumC', res.sumC, 'makespan', res.makespan, 'setup', res.setupTotal, `(${(((res.sumC - app.sumC) / app.sumC) * 100).toFixed(1)}%)`, validate(inst, res.queues));
const r = evaluate(inst, res.queues);
const cps = [960, 1920, 2880, 3840, 4800, 5760];
console.log('modules by day app :', modulesDoneBy(app.modEnd, cps).join(' '));
console.log('modules by day best:', modulesDoneBy(r.modEnd, cps).join(' '));
const fine: number[] = [];
for (let t = 120; t <= 5760; t += 240) fine.push(t);
const a = modulesDoneBy(app.modEnd, fine);
const b = modulesDoneBy(r.modEnd, fine);
console.log('t(min)  app best');
fine.forEach((t, i) => console.log(String(t).padStart(5), String(a[i]).padStart(4), String(b[i]).padStart(4), b[i] < a[i] ? '  <-- app ahead' : ''));
const sortedApp = Array.from(app.modEnd).sort((x, y) => x - y);
const sortedBest = Array.from(r.modEnd).sort((x, y) => x - y);
let worse = 0;
for (let i = 0; i < sortedApp.length; i++) if (sortedBest[i] > sortedApp[i]) worse++;
console.log('k-th completion worse than app for', worse, 'of', sortedApp.length, 'ranks');
console.log('first 12 completions app :', sortedApp.slice(0, 12).join(' '));
console.log('first 12 completions best:', sortedBest.slice(0, 12).join(' '));
import { lowerBound } from '../../src/core/optimizer/bounds';
const lb = lowerBound(inst);
console.log('lower bound on sumC', lb.sumC.toFixed(0), '| best', res.sumC, 'gap to bound', (((res.sumC - lb.sumC) / lb.sumC) * 100).toFixed(1) + '%', '| app gap', (((app.sumC - lb.sumC) / lb.sumC) * 100).toFixed(1) + '%', lb.note);
